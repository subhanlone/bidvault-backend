-- Records why the most recent payment attempt failed, separately from status.
--
-- The failure used to live in `status` alone: payment_intent.payment_failed
-- wrote FAILED, and POST /payments/create-intent refuses anything that is not
-- PENDING -- so a single declined card ended the sale permanently. No route back
-- for the winner, no explanation of what went wrong, and no admin action that
-- could reopen it. A declined card is an ordinary event, not a terminal state.
--
-- With the reason in its own column, `status` can return to PENDING for a retry
-- while the buyer is still told what happened last time. It is cleared whenever
-- a fresh PaymentIntent is created, so it always describes the most recent
-- attempt rather than accumulating history.
--
-- Nullable with no default: NULL reads as "no attempt has failed", which is
-- correct for every row that exists today.
--
-- Generated by `prisma migrate diff --from-migrations --to-schema-datamodel`
-- against a throwaway shadow database, then given IF NOT EXISTS by hand -- the
-- same reasoning as 20260808030000_add_auction_reserve_met, since production is
-- maintained with `db push` and may already carry the column.

ALTER TABLE "AuctionTransaction" ADD COLUMN IF NOT EXISTS "lastPaymentError" TEXT;
